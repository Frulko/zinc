// mbedTLS for the console player (ZN-792): the user configuration of both halves of mbedTLS 4 (MBEDTLS_USER_CONFIG_FILE and
// TF_PSA_CRYPTO_USER_CONFIG_FILE name this file, read after the vendored defaults). The player needs two kinds of session and nothing else:
// TLS 1.2 with EC J-PAKE (TLS-ECJPAKE-WITH-AES-128-CCM-8, the pairing) and TLS 1.3 with a pre-shared key and ECDHE on P-256
// (TLS_AES_128_GCM_SHA256, the sessions). No certificate, no RSA, no file, no thread, no clock of the day: a console core is single-threaded
// and its entropy comes from the HAL (mbedtls_platform_get_entropy in targets/<console>/player_<console>.cpp, /dev/urandom in the host build).

