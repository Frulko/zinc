function blade(ax: number, ay: number, bx: number, by: number): Blade { const b = new Blade(); b.move(ax, ay, true, 1, 1); b.move(bx, by, true, 1, 1); return b; }
function check(ok: boolean, why: string): void { if (!ok) throw new Error(why); }
