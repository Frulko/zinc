for (let i = 0; i < 100; i++) { a.update(0.016); check(a.hands[1].pinch >= 0 && a.hands[1].pinch <= 1, 'pinch range'); }
a.close(); check(a.hands.length === 0 && a.status === 0, 'close clears stale hands');
