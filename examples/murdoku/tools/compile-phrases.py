#!/usr/bin/env python3
"""Compile the reviewable clue dictionary to a Zinc module (no runtime JSON parser)."""
import json
from pathlib import Path
root = Path(__file__).resolve().parents[1]
bank = json.loads((root / 'assets/clue-dictionary.json').read_text())
assert len({f['family'] for f in bank}) == len(bank)
assert sum(len(f['templates']) for f in bank) == 400
out = '''// Generated by tools/compile-phrases.py from assets/clue-dictionary.json.
import * as K from './clues';
export class PhraseFamily {
 key = ''; kind = 0; scope = ''; target = ''; exclusive = false; negative = false; templates: string[] = [];
}
function group(key: string, kind: number, scope: string, target: string, exclusive: boolean, negative: boolean, templates: string[]): PhraseFamily {
 const f = new PhraseFamily(); f.key = key; f.kind = kind; f.scope = scope; f.target = target; f.exclusive = exclusive; f.negative = negative; f.templates = templates; return f;
}
export const PHRASE_BANK: PhraseFamily[] = [
'''
for f in bank:
    assert len(f['templates']) == 10 and len(set(f['templates'])) == 10
    args = [json.dumps(f['family']), 'K.' + f['kind'], json.dumps(f['scope']), json.dumps(f['target']), str(f['exclusive']).lower(), str(f['negative']).lower()]
    out += ' group(' + ','.join(args) + ',[\n'
    out += ''.join('  ' + json.dumps(t, ensure_ascii=False) + ',\n' for t in f['templates'])
    out += ' ]),\n'
out += '''];
export function family(key: string): PhraseFamily {
 for (const f of PHRASE_BANK) if (f.key === key) return f;
 throw new Error('Unknown clue phrase family: '+key);
}
export function phrase(key: string, variant: number, room: string, room2: string, object: string, person: string, count: number, roomsCount: number = 0, female: boolean = false): string {
 const f = family(key); let text = f.templates[Math.abs(variant)%f.templates.length];
 const feminine = object === 'plante' || object === 'plante fleurie' || object === 'bibliothèque' || object === 'bougie' || object === 'table dressée' || object === 'cheminée' || object === 'horloge' || object === 'baignoire' || object === 'cuisinière';
 const aObject = (feminine ? 'une ' : 'un ')+object, noObject = (feminine ? 'aucune ' : 'aucun ')+object;
 text = text.split('{aObject}').join(aObject).split('{AObject}').join(aObject.substring(0,1).toUpperCase()+aObject.substring(1));
 text = text.split('{noObject}').join(noObject).split('{NoObject}').join(noObject.substring(0,1).toUpperCase()+noObject.substring(1));
 const people = count+' '+(count === 1 ? 'personne' : 'personnes');
 text = text.split('{room}').join(room).split('{room2}').join(room2).split('{object}').join(object).split('{person}').join(person);
 text = text.split('{occupy}').join(count === 1 ? 'occupait' : 'occupaient').split('{were}').join(count === 1 ? 'était' : 'étaient').split('{wereFound}').join(count === 1 ? 'se trouvait' : 'se trouvaient');
 text = text.split('{otherPeople}').join(count === 2 ? 'une autre personne' : (count-1)+' autres personnes').split('{count}').join(''+count).split('{people}').join(people).split('{others}').join(''+(count-1)).split('{roomsCount}').join(''+roomsCount);
 if (female) text = text.split('moi seul ').join('moi seule ').split('Moi seul ').join('Moi seule ').split('seul dans').join('seule dans').split('installé ').join('installée ').split('m’a vu ').join('m’a vue ');
 return text;
}
'''
(root / 'src/phrases.ts').write_text(out)
print(f'{len(bank)} families, 400 templates compiled')
