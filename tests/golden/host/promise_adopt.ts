import { Reply, Request, fetch, serve, stop } from 'zinc:net';
// then, catch and finally whose callback returns a promise (ZN-794): then and catch adopt it, finally waits for it and keeps the value
// (or takes its rejection), in the order Node prints; then fetch(u).then(r => r.text()) is a Promise<string> (a server on a free port, one process)
const later = (s: string): Promise<string> => Promise.resolve(s)
const p1: Promise<string> = Promise.resolve(1).then(n => later('then:' + n))
p1.then(s => console.log(s))
const p2: Promise<void> = Promise.resolve(2).then(n => { console.log('void then', n); return Promise.resolve() })
p2.then(() => console.log('p2 done'))
const p3: Promise<string> = Promise.reject<string>(new Error('boom')).catch(e => later('caught:' + e.message))
p3.then(s => console.log(s))
const p3b: Promise<string> = Promise.resolve('ok').catch(e => later('never'))
p3b.then(s => console.log('no error', s))
const p3c: Promise<void> = Promise.reject<void>(new Error('v')).catch(e => Promise.resolve())
p3c.then(() => console.log('void catch adopted'))
const p3d: Promise<number> = Promise.reject<number>(new Error('n')).catch(e => 7)
p3d.then(v => console.log('literal catch', v))
const p4: Promise<string> = Promise.resolve('kept').finally(() => later('ignored'))
p4.then(s => console.log('finally', s))
const p5 = Promise.resolve('x').finally(() => Promise.reject<string>(new Error('fin')))
p5.catch(e => { console.log('finally rejects', e.message); return 'r' })
const p6 = Promise.resolve('y').finally(() => { console.log('plain finally') })
p6.then(s => console.log('after plain', s))
const port = serve(0, (req: Request): Reply => ({ status: 200, body: 'hello ' + req.path, contentType: 'text/plain' }))
const body: Promise<string> = fetch('http://127.0.0.1:' + port + '/text').then(r => r.text())
body.then(s => { console.log('fetched', s); stop() })
