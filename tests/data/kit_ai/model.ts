import { equal, ok } from 'zinc:assert';
import { AiStatus, DisclosureMode, disclosureOpen, toggleDisclosure, aiStatusLabel, contextPercent, contextTone, sourceHost } from '../../../lib/std/kit/ai-model';
equal(disclosureOpen(DisclosureMode.Automatic, true), true);
equal(disclosureOpen(DisclosureMode.Automatic, false), false);
equal(disclosureOpen(DisclosureMode.Open, false), true);
equal(disclosureOpen(DisclosureMode.Closed, true), false);
let mode = toggleDisclosure(DisclosureMode.Automatic, true);
equal(mode, DisclosureMode.Closed); equal(disclosureOpen(mode, false), false); equal(disclosureOpen(mode, true), false);
mode = toggleDisclosure(mode, true); equal(mode, DisclosureMode.Open); equal(disclosureOpen(mode, false), true);
equal(aiStatusLabel(AiStatus.Pending), 'Pending'); equal(aiStatusLabel(AiStatus.Running), 'Running');
equal(aiStatusLabel(AiStatus.Done), 'Completed'); equal(aiStatusLabel(AiStatus.Failed), 'Failed'); equal(aiStatusLabel(AiStatus.Skipped), 'Skipped');
equal(contextPercent(10, 100), 10); equal(contextPercent(200, 100), 100); equal(contextPercent(-1, 100), 0);
equal(contextPercent(1, 0), 0); equal(contextPercent(NaN, 100), 0); equal(contextPercent(1, Infinity), 0);
equal(contextTone(79,100),'normal'); equal(contextTone(80,100),'warning'); equal(contextTone(95,100),'danger');
equal(sourceHost('https://www.zinc.dev/guide?next=a#top'), 'zinc.dev');
equal(sourceHost('https://name:secret@example.test:8443/a'), 'example.test:8443');
equal(sourceHost('https://[::1]:8080/a'), '[::1]:8080'); equal(sourceHost('notes.example/one'), 'notes.example');
equal(sourceHost('file:///a'), 'Local source'); equal(sourceHost(''), 'Local source');
console.log('AI models: ok');
